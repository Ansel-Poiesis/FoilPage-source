// Keep MAIN self-contained and synchronize the shared pure contract and brand tokens.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, 'browser-extension', name), 'utf8').replace(/\r\n/g, '\n');
const generatedHeader = name => `/* Generated by node build/sync-extension-main.cjs from ${name}; do not edit directly. */\n/* Copyright (c) 2026 Ansel */\n/* SPDX-License-Identifier: MPL-2.0 */\n`;

require('../browser-extension/ui-contract.js');
const {BRAND} = globalThis.FoilPageContract;
const expectedMain = '// Generated by node build/sync-extension-main.cjs; edit douyin-hosts.js or content-main-hook.js.\n'
  + read('douyin-hosts.js').trimEnd() + '\n\n' + read('content-main-hook.js').trimEnd() + '\n';
const baseBrand = `:root {
  --fp-accent:${BRAND.dark.green.primary};
  --fp-on-accent:${BRAND.dark.green.onPrimary};
  --fp-text:${BRAND.feedback.text};
  --fp-text2:${BRAND.feedback.text2};
  --fp-muted:${BRAND.feedback.muted};
  --fp-border:${BRAND.feedback.border};
  --fp-focus:${BRAND.feedback.focus};
  --fp-pill-bg:${BRAND.pill.background};
  --fp-pill-border:${BRAND.pill.border};
  --fp-pill-text:${BRAND.pill.text};
  --fp-pill-done-bg:${BRAND.pill.doneBackground};
  --fp-pill-done-text:${BRAND.pill.doneText};
  --fp-pill-done-border:${BRAND.pill.doneBorder};
  --fp-pill-error-bg:${BRAND.pill.errorBackground};
  --fp-pill-error-border:${BRAND.pill.errorBorder};
  --fp-pill-error-text:${BRAND.pill.errorText};
  --fp-content-bg:${BRAND.content.cardBackground};
  --fp-content-text:${BRAND.content.cardText};
  --fp-content-border:${BRAND.content.cardBorder};
  --fp-content-dot:${BRAND.content.dot};
  --fp-content-dot-glow:${BRAND.content.dotGlow};
  --fp-content-hint:${BRAND.content.hint};
  --fp-content-on-accent:${BRAND.content.onAccent};
  --fp-content-button-border:${BRAND.content.buttonBorder};
  --fp-content-secondary-text:${BRAND.content.secondaryText};
  --fp-content-focus:${BRAND.content.focus};
  --fp-content-error-bg:${BRAND.content.errorBackground};
  --fp-content-error-border:${BRAND.content.errorBorder};
}
`;
const popupVariables = palette => `  --fp-popup-paper:${palette.paper};
  --fp-popup-surface:${palette.surface};
  --fp-popup-wash:${palette.wash};
  --fp-popup-line:${palette.line};
  --fp-popup-ink:${palette.ink};
  --fp-popup-muted:${palette.muted};
  --fp-popup-accent:${palette.accent};
  --fp-popup-primary:${palette.primary};
  --fp-popup-primary-hover:${palette.primaryHover};
  --fp-popup-on-primary:${palette.onPrimary};
  --fp-popup-success-bg:${palette.successBg};
  --fp-popup-warn:${palette.warn};
  --fp-popup-warn-bg:${palette.warnBg};
  --fp-popup-error:${palette.error};
  --fp-popup-error-bg:${palette.errorBg};
`;
const accentRules = ['dark', 'paper'].flatMap(theme => Object.entries(BRAND[theme])
  .map(([accent, values]) => `body[data-theme="${theme}"][data-accent="${accent}"] {
  --primary:${values.primary};
  --primary-hover:${values.hover};
  --primary-dim:${values.dim};
  --primary-soft:${values.soft};
  --on-primary:${values.onPrimary};
}
`)).join('');
const outputs = [
  {
    target: path.join(root, 'browser-extension', 'content-main.js'),
    expected: expectedMain,
    message: 'MAIN entry is stale; run node build/sync-extension-main.cjs',
  },
  {
    target: path.join(root, 'app', 'webview_ui', 'js', 'ui-contract.js'),
    expected: read('ui-contract.js'),
    message: 'desktop contract is stale; run node build/sync-extension-main.cjs',
  },
  {
    target: path.join(root, 'browser-extension', 'brand.css'),
    expected: generatedHeader('ui-contract.js') + baseBrand + ':root {\n' + popupVariables(BRAND.popup.light) + '}\n'
      + '@media (prefers-color-scheme: dark) {\n:root {\n' + popupVariables(BRAND.popup.dark) + '}\n}\n',
    message: 'extension brand tokens are stale; run node build/sync-extension-main.cjs',
  },
  {
    target: path.join(root, 'app', 'webview_ui', 'css', 'brand.css'),
    expected: generatedHeader('ui-contract.js') + baseBrand + accentRules,
    message: 'desktop brand tokens are stale; run node build/sync-extension-main.cjs',
  },
];
const normalized = target => fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n');
if (process.argv.includes('--check')) {
  for (const output of outputs) {
    if (normalized(output.target) !== output.expected) throw new Error(output.message);
  }
} else {
  for (const output of outputs) fs.writeFileSync(output.target, output.expected, 'utf8');
}
