// Keep the MAIN entry self-contained while the host policy has one source.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => fs.readFileSync(path.join(root, 'browser-extension', name), 'utf8').replace(/\r\n/g, '\n');
const expected = '// Generated by node build/sync-extension-main.cjs; edit douyin-hosts.js or content-main-hook.js.\n'
  + read('douyin-hosts.js').trimEnd() + '\n\n' + read('content-main-hook.js').trimEnd() + '\n';
const target = path.join(root, 'browser-extension', 'content-main.js');
if (process.argv.includes('--check')) {
  if (read('content-main.js') !== expected) {
    throw new Error('MAIN entry is stale; run node build/sync-extension-main.cjs');
  }
} else {
  fs.writeFileSync(target, expected, 'utf8');
}
